def _codex_plugin_command(command: str) -> str:
    for interpreter in ("python3 -B ", "python3 "):
        if not command.startswith(interpreter):
            continue
        tail = command[len(interpreter):]
        if not tail.startswith(("claude/hooks/", "harness/bin/")):
            return command
        script, separator, rest = tail.partition(" ")
        rewritten = f'{interpreter}"${{PLUGIN_ROOT}}/{script}"'
        if separator:
            rewritten += " " + rest
        return rewritten
    return command


def _render_codex_plugin_hooks(manifest: dict[str, Any]) -> str:
    hooks: dict[str, list[dict[str, Any]]] = {}
    bash_sources: list[str] = []
    bash_timeouts: list[int] = []
    for hook in manifest.get("hooks", []):
        host = hook.get("hosts", {}).get("codex", {})
        if host.get("status") != "ready":
            continue
        for event in host.get("events", []):
            if event.get("event") == "PreToolUse" and event.get("matcher") == "Bash":
                bash_sources.append(hook["source"])
                if event.get("timeout_seconds") is not None:
                    bash_timeouts.append(event["timeout_seconds"])

    dispatcher_rendered = False
    for hook in manifest.get("hooks", []):
        host = hook.get("hosts", {}).get("codex", {})
        if host.get("status") != "ready":
            continue
        for event in host.get("events", []):
            if event.get("event") == "PreToolUse" and event.get("matcher") == "Bash":
                if dispatcher_rendered:
                    continue
                command = (
                    'python3 -B "${PLUGIN_ROOT}/claude/hooks/'
                    'codex_pretool_dispatch.py"'
                )
                command += "".join(
                    f" --gate {shlex.quote(source)} --gate-timeout {timeout}"
                    for source, timeout in zip(
                        bash_sources, bash_timeouts, strict=True
                    )
                )
                item = {
                    "matcher": "Bash",
                    "hooks": [{"type": "command", "command": command}],
                }
                if bash_timeouts:
                    item["hooks"][0]["timeout"] = sum(bash_timeouts) + (
                        len(bash_timeouts) * CODEX_DISPATCH_OVERHEAD_SECONDS_PER_GATE
                    )
                hooks.setdefault("PreToolUse", []).append(item)
                dispatcher_rendered = True
                continue
            item: dict[str, Any] = {
                "matcher": event.get("matcher", ""),
                "hooks": [
                    {
                        "type": "command",
                        "command": _codex_plugin_command(event["command"]),
                    }
                ],
            }
            timeout = event.get("timeout_seconds")
            if timeout is not None:
                item["hooks"][0]["timeout"] = timeout
            hooks.setdefault(event["event"], []).append(item)
    return json.dumps({"hooks": hooks}, indent=2, sort_keys=True) + "\n"


