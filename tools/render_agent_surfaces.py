# Deployed-path -> vendored-plugin-path rewrites. Order matters: the more
# specific harness/bin prefix is checked before the generic hooks prefix.
# Args after the script (e.g. `--quiet`) are preserved.
_PLUGIN_PATH_REWRITES = (
    ("~/.claude/harness/bin/", "${CLAUDE_PLUGIN_ROOT}/harness/bin/"),
    ("~/.claude/hooks/", "${CLAUDE_PLUGIN_ROOT}/hooks/"),
)


def _claude_plugin_command(command: str) -> str:
    # Rewrite a deployed ~/.claude/{hooks,harness/bin}/<script> command to its
    # vendored plugin path. Commands outside those managed paths pass through.
    for prefix, repl in _PLUGIN_PATH_REWRITES:
        if prefix in command:
            head, tail = command.split(prefix, 1)
            script, sep, rest = tail.partition(" ")
            rebuilt = f'{head}"{repl}{script}"'
            if sep:
                rebuilt += " " + rest
            return rebuilt
    return command


def _render_claude_plugin_hooks(manifest: dict[str, Any]) -> str:
    hooks: dict[str, list[dict[str, Any]]] = {}
    for hook in manifest.get("hooks", []):
        host = hook.get("hosts", {}).get("claude", {})
        if host.get("status") != "ready":
            continue
        for event in host.get("events", []):
            command = event.get("command")
            if not command:
                continue
            item: dict[str, Any] = {
                "matcher": event.get("matcher", ""),
                "hooks": [
                    {"type": "command", "command": _claude_plugin_command(command)}
                ],
            }
            timeout = event.get("timeout_seconds")
            if timeout is not None:
                item["hooks"][0]["timeout"] = timeout
            hooks.setdefault(event["event"], []).append(item)
    # Always-on rules injection (the rules extension point for plugins).
    hooks.setdefault("SessionStart", []).append({
        "matcher": "startup|clear|compact",
        "hooks": [
            {
                "type": "command",
                "command": 'bash "${CLAUDE_PLUGIN_ROOT}/hooks/inject-rules.sh"',
            }
        ],
    })
    return json.dumps({"hooks": hooks}, indent=2, sort_keys=True) + "\n"


